#!/usr/bin/env node
// Create a new family tree that runs on this engine.
//
//   node tools/tree-init.mjs --dir ../smith-family --id smith-family --title "Smith Family" [--gedcom smith.ged] [--link-node-modules]
//
// Copies the engine's committed files (at --ref, default HEAD) (tools/, lib/, app/, assets/, the viewer
// shell and package files; never evidence/, tree/, data/ or this tree's
// runbooks), writes a tree.config.json, an empty consents.json (every
// outward-facing helper off), the generic AGENTS.md / GOAL.md / DECISIONS.md
// from templates/tree/, and an empty canonical store. With --gedcom the store
// is seeded by tools/gedcom-import.mjs. The new directory gets its own Git
// repository; nothing is pushed anywhere.

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { STORE_SCHEMA_VERSION, TREE_CONFIG_SCHEMA_VERSION, VIEWER_BRANDING_FILE, engineRoot, viewerBrandingSource } from "./tree-config.mjs";
import { countriesInGedcom, planImport, writeImport } from "./gedcom-import.mjs";
import { baseCountryFlags, countryCodes } from "./place-labels.mjs";
import { EMPTY_LEGACY_SHA256, TREE_RECENCY_POLICY_ID } from "./tree-recency-policy.mjs";
import { buildExtractionCampaign } from "./extraction-store.mjs";

// Engine paths copied into a new tree. Everything else in this repository is
// this tree's own data or history.
export const ENGINE_COPY_PATHS = ["tools", "lib", "app", "assets", "index.html", "middleware.js", "next.config.mjs", "package.json", "package-lock.json", "vercel.json", "favicon.svg", ".gitignore", "TREE-SETUP.md", "templates"];
// Tree-specific material inside those paths that must not travel.
export const ENGINE_COPY_EXCLUDES = [/^tools\/migrations\//];

const BRANCH_ID = "imported-tree";

// Engine files as committed at `ref`, so another session's unfinished work in
// the shared checkout never travels into a new tree.
export function engineFiles(root = engineRoot, ref = "HEAD") {
  const result = spawnSync("git", ["ls-tree", "-r", "-z", "--name-only", ref, "--", ...ENGINE_COPY_PATHS], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`git ls-tree failed: ${result.stderr}`);
  return result.stdout.split("\0").filter(Boolean).filter((file) => !ENGINE_COPY_EXCLUDES.some((pattern) => pattern.test(file)));
}

function committedFile(root, ref, file) {
  const result = spawnSync("git", ["show", `${ref}:${file}`], { cwd: root, maxBuffer: 256 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(`git show ${ref}:${file} failed: ${result.stderr}`);
  return result.stdout;
}

function write(dir, relative, value) {
  const file = path.join(dir, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, typeof value === "string" ? value : `${JSON.stringify(value, null, 2)}\n`);
}

export function treeConfigFor({ id, title, rootPersonIds = [], primaryCheckout = null }) {
  return {
    schemaVersion: TREE_CONFIG_SCHEMA_VERSION,
    store: { schemaVersion: STORE_SCHEMA_VERSION },
    tree: { id, title, rootPersonIds, homePersonIds: [] },
    scopes: { default: "main", additional: [], dormant: [] },
    paths: { primaryCheckout, desktopMirror: null, recordArchive: null },
    viewer: { title: `${title} Tree`, shortTitle: title, subtitle: `${title} history`, requireFlags: false },
    vercel: { scope: null },
    consentsFile: "consents.json",
    engineBoundary: { terms: [], baselineFile: "tree/engine-boundary-baseline.json" }
  };
}

