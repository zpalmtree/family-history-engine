export function initTree({ dir, id, title, gedcom = null, linkNodeModules = false, root = engineRoot, ref = "HEAD", today = new Date().toISOString().slice(0, 10) }) {
  const target = path.resolve(dir);
  if (fs.existsSync(target) && fs.readdirSync(target).length) throw new Error(`${target} is not empty`);
  if (!/^[a-z0-9][a-z0-9-]{0,63}$/.test(id || "")) throw new Error("--id must be a lower-case slug");
  if (!title?.trim()) throw new Error("--title is required");
  fs.mkdirSync(target, { recursive: true });

  for (const file of engineFiles(root, ref)) {
    const to = path.join(target, file);
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.writeFileSync(to, committedFile(root, ref, file));
  }
  for (const name of ["AGENTS.md", "GOAL.md", "DECISIONS.md"]) {
    const committed = path.join(target, "templates", "tree", name);
    fs.copyFileSync(fs.existsSync(committed) ? committed : path.join(root, "templates", "tree", name), path.join(target, name));
  }

  let rootPersonIds = [];
  let plan = null;
  // Everyone imported becomes visible now; the recency ledger records it.
  const treeAddedAt = `${new Date().toISOString().slice(0, 19)}+00:00`;
  let countries = [];
  if (gedcom) {
    const text = fs.readFileSync(gedcom, "utf8");
    countries = countriesInGedcom(text).filter((name) => !Object.hasOwn(baseCountryFlags, name));
    plan = planImport(text, { fileName: gedcom, branchId: BRANCH_ID, today, treeAddedAt, countries });
    if (plan.rootPersonId) rootPersonIds = [plan.rootPersonId];
  }
  const packageFile = path.join(target, "package.json");
  const pkg = JSON.parse(fs.readFileSync(packageFile, "utf8"));
  pkg.name = id;
  write(target, "package.json", pkg);
  const lockFile = path.join(target, "package-lock.json");
  if (fs.existsSync(lockFile)) {
    const lock = JSON.parse(fs.readFileSync(lockFile, "utf8"));
    lock.name = id;
    if (lock.packages?.[""]) lock.packages[""].name = id;
    write(target, "package-lock.json", lock);
  }
  const enginePackage = JSON.parse(committedFile(root, ref, "package.json").toString("utf8"));
  const engine = { version: enginePackage.version || null, source: enginePackage.repository?.url || null };
  write(target, "tree.config.json", { ...treeConfigFor({ id, title, rootPersonIds, primaryCheckout: target }), engine, places: { countries: countries.map((name) => ({ name, flag: countryCodes[name] || null })) } });
  write(target, VIEWER_BRANDING_FILE, viewerBrandingSource({ title, issuer: id }));
  write(target, "consents.json", { schemaVersion: 1, note: "Outward-facing helpers this tree's owner has switched on. All are off in a new tree; see TREE-SETUP.md.", capabilities: {} });
  for (const [relative, value] of Object.entries(emptyStore({ title, rootPersonIds }))) write(target, relative, value);
  write(target, "evidence/research/tree-recency-baseline.json", {
    schemaVersion: 2,
    policyId: TREE_RECENCY_POLICY_ID,
    grandfatheredAt: treeAddedAt,
    note: "Append-only first-visibility ledger. This tree grandfathers nobody; each entry records the first time a person entered a tree view and must match the person's treeAddedAt.",
    legacySnapshotSha256: EMPTY_LEGACY_SHA256,
    legacyVisiblePersonIds: [],
    firstVisibleEntries: (plan?.people || []).map((person) => ({ personId: person.personId, firstVisibleAt: treeAddedAt }))
  });
  if (plan) writeImport(plan, target);
  if (linkNodeModules && fs.existsSync(path.join(root, "node_modules"))) fs.symlinkSync(path.join(root, "node_modules"), path.join(target, "node_modules"), "dir");

  const git = (...args) => spawnSync("git", args, { cwd: target, encoding: "utf8" });
  if (git("init", "-q", "-b", "main").status !== 0) git("init", "-q");
  // A first local commit (never pushed) so the engine can read its own files at HEAD.
  git("add", "-A");
  const committed = git("commit", "-q", "-m", `Start ${title} on the family-history engine`).status === 0;
  return { target, rootPersonIds, committed, people: plan?.people.length || 0, questions: plan?.questions.length || 0 };
}

function main() {
  const args = process.argv.slice(2);
  const value = (flag) => { const index = args.indexOf(flag); return index >= 0 ? args[index + 1] : undefined; };
  const dir = value("--dir");
  if (!dir) throw new Error("usage: node tools/tree-init.mjs --dir <new dir> --id <slug> --title <title> [--gedcom <file.ged>] [--link-node-modules]");
  const result = initTree({ dir, id: value("--id"), title: value("--title"), gedcom: value("--gedcom"), ref: value("--ref") || "HEAD", linkNodeModules: args.includes("--link-node-modules") });
  console.log(`New tree at ${result.target}${result.people ? ` with ${result.people} imported people and ${result.questions} parent-link questions` : ""}.`);
  console.log(`Root people: ${result.rootPersonIds.join(", ") || "(none yet: set tree.rootPersonIds in tree.config.json)"}.`);
  if (!result.committed) console.log("Git could not make the first commit (set user.name and user.email), so commit the new tree yourself.");
  console.log("Next: cd into it, run npm install, then npm run build and node tools/check-new-tree.mjs. See TREE-SETUP.md.");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}
